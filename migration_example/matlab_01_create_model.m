%% Create and calibrate a model object from the source file


%% Create model object from source file

model = Model.fromFile( ...
    fullfile("model_files", "matlab_closed_economy_qpm.model"), ...
    linear=false, ...
    growth=true, ...
    comment="Closed economy QPM" ...
);


%% Assign parameters
% Same calibration as calibrate_parameters.db.py; no Python runtime needed.
% Name-value assignment checks that every name exists in the model.

% Steady-state parameters
model = assign( ...
    model, ...
    ss_rrs=0, ...
    ss_ad_cpi=2, ...
    ss_ad_y=1.5 ...
);

% Dynamic parameters
model = assign( ...
    model, ...
    c0_y_gap=0.75, ...
    c1_y_gap=0.10, ...
    c0_ad_cpi=0.55, ...
    c1_ad_cpi=0.10, ...
    c1_ad_cpi_ste=1, ...
    c2_ad_cpi_ste=0.1, ...
    c0_rs=0.75, ...
    c0_rrs_tnd=0.95, ...
    c1_mpr=4, ...
    c0_ad_y_tnd=0.95 ...
);

% Standard deviations of shocks
model = assign( ...
    model, ...
    std_shk_ad_y_tnd=3, ...
    std_shk_y_gap=1.0, ...
    std_shk_ad_cpi=2.0, ...
    std_shk_rs=0.3, ...
    std_shk_ad_cpi_ste=0.1, ...
    std_shk_rrs_tnd=0.5 ...
);

% Standard deviations of measurement errors
model = assign( ...
    model, ...
    std_shk_obs_y=0, ...
    std_shk_obs_cpi=0, ...
    std_shk_obs_rs=0 ...
);


%% Print the parameters from within the model

parametersAssigned = access(model, "parameters");
disp("Parameters assigned to the model:");
disp(parametersAssigned);


%% Calculate steady state, including nonzero steady-state changes

model = steady(model);
checkSteady(model);


%% Calculate steady state with y=1 and cpi=1
% Assign levels only, preserving the previously calculated changes.
% fixLevel is the Iris Toolbox counterpart of SteadyPlan.fix_level.

model = assign(model, "-level", y=1, cpi=1);
model = steady( ...
    model, ...
    fixLevel=["y", "cpi"] ...
);
checkSteady(model);

steadyTable = table( ...
    model, ["steadyLevel", "steadyChange"], ...
    writeTable=fullfile("data_files", "steadyTable.csv") ...
);

disp("Steady-state values:");
disp(steadyTable);


%% Calculate first-order solution matrices

model = solve(model);


%% Save model object to a MAT file instead of a Python pickle

save(fullfile("mat_files", "matlab_model.mat"), "model");

